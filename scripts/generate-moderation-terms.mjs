#!/usr/bin/env node
/**
 * Rebuilds the committed reserved-name module and the moderation_terms INSERT
 * block. Run after bumping obscenity or @dsojevic/profanity-list.
 *
 *   node scripts/generate-moderation-terms.mjs
 *
 * Sources (all MIT), snapshotted 22 Nov 2026:
 * - obscenity 0.4.6 (jo3-l) — leetspeak, confusables, and repeat collapsing.
 *   The English dataset is not loaded; its patterns match inside Penistone and Dickson.
 * - @dsojevic/profanity-list 1.0.0 — severity 3–4 block, 1–2 review. Stars mean
 *   "previous character one or more" and are stripped to the base spelling.
 * - shouldbee/reserved-usernames and marteinn/The-Big-Username-Blocklist.
 * LDNOOBW, mvila/profanity-list, bad-words, and the coffee-and-fun list are not used.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import list from '@dsojevic/profanity-list'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dataDir = path.join(root, 'src/lib/moderation/data')

const EXTRA_RESERVED = [
  'dashboard', 'login', 'register', 'onboard', 'superadmin', 'booking',
  'payment-confirmed', 'api', 'app', 'business', 'auth', 'help', 'pricing',
  'billing', 'signup', 'sign-up', 'signin', 'sign-in', 'admin', 'www', 'mail',
  'support', 'staff', 'team', 'official', 'verified', 'styleflo', 'stylefloai',
  'style-flo', 'styleflo-ai', 'widget', 'embed', 'terms', 'privacy', 'account',
  'settings', 'null', 'undefined',
]

const IMPERSONATION_EXACT = [
  'support', 'official', 'staff', 'team', 'admin', 'verified', 'styleflo',
  'stylefloai', 'styleflo support', 'styleflo official', 'official support',
  'styleflo staff', 'styleflo team', 'styleflo admin', 'styleflo verified',
]

const BRAND_TOKENS = ['styleflo', 'stylefloai']

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`
}

function normaliseReserved(raw) {
  return String(raw)
    .trim()
    .toLowerCase()
    .normalize('NFKC')
    .replace(/^@/, '')
    .replace(/[^a-z0-9]+/g, '')
}

function bases(match) {
  return [...new Set(
    String(match)
      .split('|')
      .map((part) => part.trim().toLowerCase().replace(/\*/g, ''))
      .filter((part) => part.length >= 3 && /^[\p{L}\p{N} '’-]+$/u.test(part)),
  )]
}

const reserved = new Set()
for (const file of ['shouldbee-reserved-usernames.txt', 'big-username-blocklist.txt']) {
  const text = fs.readFileSync(path.join(dataDir, file), 'utf8')
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const key = normaliseReserved(trimmed)
    if (key.length >= 2) reserved.add(key)
  }
}
for (const extra of EXTRA_RESERVED) {
  const key = normaliseReserved(extra)
  if (key.length >= 2) reserved.add(key)
}

const mustStayOpen = [
  'acmecorp', 'myworkspace', 'scunthorpehairco', 'cockburnbeauty', 'glamourpuss',
  'hairkuts', 'penistone', 'dickson', 'cockburn', 'scunthorpe', 'essex', 'hancock',
]
for (const key of mustStayOpen) {
  if (reserved.has(key)) {
    console.error(`Refusing to reserve a name the product must accept: ${key}`)
    process.exit(1)
  }
}

const reservedSorted = [...reserved].sort()
const reservedModule = `/* Generated by scripts/generate-moderation-terms.mjs. Do not edit by hand. */
export const RESERVED_SLUGS: readonly string[] = [
${reservedSorted.map((term) => `  ${JSON.stringify(term)},`).join('\n')}
]
`
fs.writeFileSync(path.join(root, 'src/lib/moderation/reserved-names.ts'), reservedModule)

const profanity = new Map()
for (const item of list.en) {
  const severity = Number(item.severity)
  const action = severity >= 3 ? 'block' : 'review'
  for (const term of bases(item.match)) {
    const current = profanity.get(term)
    if (!current || severity > current.severity) {
      profanity.set(term, { severity, action })
    }
  }
}

const rows = []
for (const [term, meta] of profanity) {
  rows.push({ term, kind: 'profanity', severity: meta.severity, action: meta.action })
}
for (const term of reservedSorted) {
  rows.push({ term, kind: 'reserved', severity: 0, action: 'reserved' })
}
for (const term of IMPERSONATION_EXACT) {
  rows.push({ term, kind: 'impersonation', severity: 4, action: 'block' })
}
for (const term of BRAND_TOKENS) {
  rows.push({ term, kind: 'brand_token', severity: 4, action: 'block' })
}

const values = rows.map((row) => (
  `  (${sqlString(row.term)}, ${sqlString(row.kind)}, ${row.severity}, ${sqlString(row.action)}, 'seed')`
)).join(',\n')

const insertSql = `-- Generated by scripts/generate-moderation-terms.mjs. Do not edit by hand.
INSERT INTO public.moderation_terms (term, kind, severity, action, source)
VALUES
${values}
ON CONFLICT (term, kind) DO NOTHING;
`

const out = path.join(root, 'src/lib/moderation/data/moderation-terms.insert.sql')
fs.writeFileSync(out, insertSql)
console.log(`reserved ${reservedSorted.length}, profanity ${profanity.size}, rows ${rows.length}`)
