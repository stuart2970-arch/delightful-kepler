#!/usr/bin/env node
/**
 * STYL-210: Write .env.local and .env.test from the local Supabase CLI stack.
 * Never writes live project URLs or live third-party API keys.
 *
 * Usage:
 *   npx supabase start
 *   npm run env:local
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const LIVE_REF = 'tkoasyjvrgaglofpzduq';

function fail(message) {
  console.error(`[env:local] ${message}`);
  process.exit(1);
}

function readSupabaseStatus() {
  try {
    const raw = execFileSync('npx', ['supabase', 'status', '-o', 'json'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    return JSON.parse(raw);
  } catch {
    fail(
      'Could not read local Supabase status. Start it first with `npx supabase start`, then re-run `npm run env:local`.',
    );
  }
}

function pick(status, ...keys) {
  for (const key of keys) {
    if (status[key]) return status[key];
  }
  return undefined;
}

function buildEnvFile({ apiUrl, anon, service, appUrl, appEnv, playwright }) {
  const lines = [
    '# Generated by `npm run env:local` (STYL-210).',
    '# Points at the LOCAL Supabase CLI stack only. Do NOT paste live keys here.',
    `APP_ENV=${appEnv}`,
    `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}`,
    `SUPABASE_URL=${apiUrl}`,
    `SUPABASE_ANON_KEY=${anon}`,
    `SUPABASE_SERVICE_ROLE_KEY=${service}`,
    `NEXT_PUBLIC_APP_URL=${appUrl}`,
    `NEXT_PUBLIC_SITE_URL=${appUrl}`,
    // Third-party keys: mock / test only — never live credentials on a dev machine.
    'STRIPE_SECRET_KEY=sk_test_mock',
    'MAILGUN_API_KEY=mock_mailgun_api_key_for_local_testing',
    'MAILGUN_DOMAIN=localhost.local',
    'GEMINI_API_KEY=mock-test-key',
    'GOOGLE_GENERATIVE_AI_API_KEY=mock-test-key',
    'OPENAI_API_KEY=mock-test-key',
    'VAPI_API_KEY=mock-vapi-key',
    'VAPI_PRIVATE_API_KEY=mock-vapi-key',
    'VAPI_SECRET_KEY=mock-vapi-key',
    'NEXT_PUBLIC_VAPI_PUBLIC_KEY=mock-vapi-public-key',
    'VAPI_PUBLIC_KEY=mock-vapi-public-key',
    'VAPI_MASTER_ASSISTANT_ID=00000000-0000-0000-0000-0000000000va',
    'STRIPE_WEBHOOK_SECRET=whsec_test_local_mock_secret',
    'TWILIO_ACCOUNT_SID=ACmocktwilioaccountsid000000000000',
    'TWILIO_AUTH_TOKEN=mock_twilio_auth_token',
    'META_APP_SECRET=test_meta_app_secret_123',
    'META_VERIFY_TOKEN=styleflo_meta_verify_2026',
    'CRON_SECRET=mock_cron_secret_for_local_testing',
    // Cloudflare Turnstile always-pass test keys (safe for local/dev).
    'TURNSTILE_SECRET_KEY=1x0000000000000000000000000000000AA',
    'CLOUDFLARE_TURNSTILE_SECRET_KEY=1x0000000000000000000000000000000AA',
    'NEXT_PUBLIC_TURNSTILE_SITE_KEY=1x0000000000000000000000000000000AA',
  ];
  if (playwright) {
    lines.push('PLAYWRIGHT_TEST=true');
    lines.push('NODE_ENV=test');
    // Production default is 20/15min. The suite shares one IP against a
    // 15-minute window, so tests need a high ceiling. Do not copy this to Cloud Run.
    lines.push('AUTH_RATE_LIMIT_PER_IP=10000');
  }
  lines.push('');
  return lines.join('\n');
}

const status = readSupabaseStatus();
const apiUrl = pick(status, 'API_URL', 'apiUrl') || 'http://127.0.0.1:54321';
const anon = pick(status, 'ANON_KEY', 'anonKey');
const service = pick(status, 'SERVICE_ROLE_KEY', 'serviceRoleKey');

if (!anon || !service) {
  fail(`Missing local Supabase keys. Status keys: ${Object.keys(status).join(', ')}`);
}

if (new RegExp(LIVE_REF, 'i').test(apiUrl) || /supabase\.co/i.test(apiUrl)) {
  // Local CLI never reports a *.supabase.co host; refuse anything that looks cloud-hosted.
  fail(`Refusing to write env files against a non-local Supabase URL: ${apiUrl}`);
}

const localDev = buildEnvFile({
  apiUrl,
  anon,
  service,
  appUrl: 'http://localhost:3000',
  appEnv: 'development',
  playwright: false,
});

const localTest = buildEnvFile({
  apiUrl,
  anon,
  service,
  appUrl: 'http://localhost:3001',
  appEnv: 'test',
  playwright: true,
});

fs.writeFileSync(path.join(root, '.env.local'), localDev, 'utf8');
fs.writeFileSync(path.join(root, '.env.test'), localTest, 'utf8');

console.log('[env:local] Wrote .env.local and .env.test for local Supabase only.');
console.log(`[env:local] NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`);
console.log('[env:local] Third-party keys are mocks — safe for local development and tests.');
